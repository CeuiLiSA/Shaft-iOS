#!/usr/bin/env python3
"""Sync the October 5–10 Android feature strings into the native iOS catalog."""
from pathlib import Path
import json
import re
import xml.etree.ElementTree as ET

root = Path(__file__).resolve().parents[1]
android = root.parent / "Pixiv-Shaft"
locales = {"en": "values-en", "zh-Hans": "values", "zh-Hant": "values-zh-rTW",
           "ja": "values-ja", "ko": "values-ko", "ru": "values-ru", "tr": "values-tr"}
prefixes = ("illust_list_layout", "webdav_", "app_lock_", "applock_", "download_toast_", "ai_translate_unsaved_",
            "ai_block_exempt_", "setting_read_timeout_", "settings_scroll_edge_haptic")
extras = {"show_illust_card_bookmark_button_setting", "comic_reader_landscape_tap_flip",
          "dlmgr_active_size_unknown", "dlmgr_active_size_stalled", "aria2_btn_save", "aria2_btn_test", "aria2_saved"}

def read(directory):
    result = {}
    for module in ("app", "applock"):
        for file in sorted((android / module / "src/main/res" / directory).glob("*.xml")):
            for node in ET.parse(file).getroot().findall("string"):
                if node.attrib.get("translatable") == "false":
                    continue
                name = node.attrib["name"]
                if name.startswith(prefixes) or name in extras:
                    value = "".join(node.itertext()).replace("\\n", "\n").replace("\\'", "'")
                    result[name] = re.sub(r"%(\d+\$)?s", r"%\1@", value)
    return result

def key(name):
    parts = name.split("_")
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])

base = read("values")
lines = ["// Generated by scripts/sync-october-port-strings.py. Android 2026-10-05…10.",
         "import Foundation", "", "enum OctoberPortStrings {",
         "    static let table: [String: [LocalizedKey: String]] = ["]
for tag, directory in locales.items():
    entries = read(directory)
    # Platform-only adaptation: iOS protects previews while inactive, and its
    # background execution is scheduled by the OS rather than an exact daily timer.
    entries["app_lock_desc"] = re.sub(r"\s+(On|На)$", "", entries["app_lock_desc"].split("Android")[0].rstrip(" .;；。"))
    schedule_note = {
        "en": "iOS schedules background runs based on app usage; they may be delayed.",
        "zh-Hans": "iOS 根据使用情况安排后台运行，可能延后。",
        "zh-Hant": "iOS 依使用情況安排背景執行，可能延後。",
        "ja": "iOS が使用状況に応じてバックグラウンド実行を調整するため、遅れる場合があります。",
        "ko": "iOS가 사용 상황에 따라 백그라운드 실행을 예약하므로 지연될 수 있습니다.",
        "ru": "iOS планирует фоновый запуск с учётом использования приложения; возможна задержка.",
        "tr": "iOS arka plan çalışmasını uygulama kullanımına göre planlar; gecikebilir.",
    }
    entries["webdav_auto_backup_desc"] += "\n" + schedule_note[tag]
    pinned_names = {
        "en": [("pinned artists", "pinned tags")],
        "zh-Hans": [("置顶作者", "置顶标签")], "zh-Hant": [("置頂作者", "置頂標籤")],
        "ja": [("ピン留めしたユーザー", "ピン留めしたタグ")], "ko": [("고정한 작가", "고정한 태그")],
        "ru": [("закреплённых авторов", "закреплённые теги"), ("закреплённые авторы", "закреплённые теги")],
        "tr": [("sabitlenen sanatçıları", "sabitlenen etiketleri"), ("sabitlenen sanatçılar", "sabitlenen etiketler")],
    }
    for name in ("webdav_intro_body", "webdav_restore_confirm_message"):
        for old, new in pinned_names[tag]:
            entries[name] = entries[name].replace(old, new)
    entries["ai_block_exempt_hint"] = entries["ai_block_exempt_hint"].split("\n")[0]
    missing = set(base) - set(entries)
    if missing:
        raise SystemExit(f"Missing strings in {directory}: {sorted(missing)}")
    lines.append(f'        "{tag}": [')
    for name in sorted(base):
        lines.append(f"            .{key(name)}: {json.dumps(entries[name], ensure_ascii=False)},")
    lines.append("        ],")
lines += ["    ]", "}", ""]
(root / "Shaft-iOS/Localization/OctoberPortStrings.swift").write_text("\n".join(lines))
enum_file = root / "Shaft-iOS/Localization/LocalizedKey.swift"
content = enum_file.read_text()
missing_keys = [key(name) for name in sorted(base) if not re.search(r"\b" + key(name) + r"\b", content)]
if missing_keys:
    at = content.rfind("}")
    content = content[:at] + "    // Android 2026-10-05…10 feature parity\n    case " + ", ".join(missing_keys) + "\n" + content[at:]
    enum_file.write_text(content)
print(f"Synced {len(base)} keys in {len(locales)} languages.")
