#!/usr/bin/env python3
"""Generate an explicit typed allowlist from the two apps' preference models."""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
swift = (root / "Shaft-iOS/More/AppSettingsStore.swift").read_text()
java = (root.parent / "Pixiv-Shaft/app/src/main/java/ceui/lisa/utils/Settings.java").read_text()
types = {k: {"bool": "boolean", "int": "integer", "double": "decimal", "string": "string"}[t]
         for t, k in re.findall(r'(bool|int|double|string)\("(st_[^"]+)"', swift)}
types.pop("st_downloadToastsMigrated", None)
types["st_mutedDownloadToasts"] = "strings"
types["st_aiBlockExemptAuthorIds"] = "integers"
types["st_aiBlockExemptDisabledIds"] = "integers"
types["search_default_sort_wire_v2"] = "string"
types["ui_waterfall_columns_v1"] = "integer"
types["content_hide_r18_v1"] = "boolean"
types["cmr_landscape_tap_flip"] = "boolean"
java_types = {name: kind for kind, name in re.findall(r'private\s+(?:volatile\s+)?(boolean|int|double|float|String)\s+(\w+)\s*[=;]', java)}
kind_match = {"boolean": {"boolean"}, "integer": {"int"}, "decimal": {"double", "float"}, "string": {"String"}}
common = [key[3:] for key, kind in types.items() if key.startswith("st_") and java_types.get(key[3:]) in kind_match.get(kind, set())]
common += ["mutedDownloadToasts", "aiBlockExemptAuthorIds", "aiBlockExemptDisabledIds"]
lines = ["// Generated by scripts/sync-backup-preferences.py. No authentication or device-local keys.",
         "import Foundation", "", "enum BackupPreferenceSchema {",
         "    enum Kind { case boolean, integer, decimal, string, strings, integers }",
         "    static let native: [String: Kind] = ["]
lines += [f'        "{key}": .{kind},' for key, kind in sorted(types.items())]
lines += ["    ]", "    static let androidCommon: Set<String> = ["]
lines += [f'        "{key}",' for key in sorted(common)]
lines += ["    ]", "}", ""]
file = root / "Shaft-iOS/Backup/BackupPreferenceSchema.swift"
file.parent.mkdir(parents=True, exist_ok=True)
file.write_text("\n".join(lines))
print(f"Allowlisted {len(types)} native preference keys and {len(common)} shared Android fields.")
